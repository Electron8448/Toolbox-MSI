import { cp, lstat, mkdir, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { categories, groups, tools } from '../src/categories/index.js';

const requestedBase = process.env.PAGES_BASE_PATH ?? '/Toolbox';
const base = requestedBase.replace(/\/$/, '');
if (!/^(?:\/[a-zA-Z0-9_.-]+)*$/.test(base) || base.split('/').some(part => part === '.' || part === '..')) {
  throw new Error('PAGES_BASE_PATH must be empty for a root site or a path such as /Toolbox.');
}

const args = process.argv.slice(2);
if (args.length > 1 || (args.length && args[0] !== '--docs')) {
  throw new Error('Usage: node scripts/build-pages.js [--docs]');
}
const folder = args[0] === '--docs' ? 'docs' : 'dist';
const output = new URL('../' + folder + '/', import.meta.url);

async function readOptional(url) {
  return readFile(url, 'utf8').catch(error => {
    if (error.code !== 'ENOENT') throw error;
  });
}

const previous = await lstat(new URL('../' + folder, import.meta.url)).catch(error => {
  if (error.code !== 'ENOENT') throw error;
});
let customDomain;
if (previous) {
  const root = await realpath(new URL('../', import.meta.url));
  if (!previous.isDirectory() || previous.isSymbolicLink() || await realpath(output) !== join(root, folder)) {
    throw new Error(folder + ' must be a normal directory inside Toolbox.');
  }
  if (folder === 'docs') {
    const marker = await readOptional(new URL('.toolbox-generated', output));
    if (marker !== 'Generated by Toolbox.\n') {
      throw new Error('The docs folder already exists and was not generated by Toolbox.');
    }
    customDomain = await readOptional(new URL('CNAME', output));
  }
  await rm(output, { recursive: true });
}
await mkdir(output);

const source = new URL('../src/', import.meta.url);
for (const path of ['app.js', 'readme-page.js', 'routing.js', 'tool-page.js', 'tool-results.js', 'styles.css', 'toolbox-icon.svg', 'calculator', 'categories', 'vendor']) {
  await cp(new URL(path, source), new URL(path, output), { recursive: true });
}

await cp(new URL('../README.md', import.meta.url), new URL('README.md', output));

const template = await readFile(new URL('index.html', source), 'utf8');
const html = template
  .replace('<title>Toolbox</title>', `<title>Toolbox</title>\n  <meta name="toolbox-pages-base" content="${base}">`)
  .replaceAll(/(href|src)="\/(styles\.css|app\.js|toolbox-icon\.svg)"/g, (_, attr, asset) => `${attr}="${base}/${asset}"`)
  .replaceAll(/href="\/(search)?" data-route/g, (_, search) => `href="${base}/${search ? 'search/' : ''}" data-route`);
const routes = ['/', '/search', '/readme', ...[...categories, ...groups, ...tools].map(item => item.path)];
for (const path of routes) {
  const directory = new URL('.' + (path === '/' ? '/' : path + '/'), output);
  await mkdir(directory, { recursive: true });
  await writeFile(new URL('index.html', directory), html);
}
await writeFile(new URL('.nojekyll', output), '');
if (folder === 'docs') await writeFile(new URL('.toolbox-generated', output), 'Generated by Toolbox.\n');
if (customDomain !== undefined) await writeFile(new URL('CNAME', output), customDomain);
console.log(`Built ${routes.length} Toolbox pages in ${folder}/ for ${base || '/'}.`);
